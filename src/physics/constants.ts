  /** Геометрия колёс (катков) */
  wheelRadius: 0.075,
  wheelWidth: 0.12,
  wheelMass: 3.5,

  /** Положения колёс относительно центра шасси — асимметричные.
   * CAD-ниши боковых модулей корпуса не симметричны: передние ниши заглублены
   * (передние колёса должны стоять ближе к центру по X, чтобы не «ехать на
   * бампере»), а задние ниши шире (задние колёса разнесены сильнее по Z).
   * Подобрано под разметку пользователя 2026-05-08 (зелёные стрелки наружу
   * на задних колёсах, назад — на передних). */
  wheelFrontOffsetX: 0.115, // передние колёса — глубже в передние ниши, маленький зазор от стенки
  wheelRearOffsetX: 0.32, // задние колёса — у самой кормы
  wheelFrontOffsetZ: 0.345, // передние колёса — на той же ширине, что и задние
  wheelRearOffsetZ: 0.345, // задние колёса — внутри задних боковых проёмов
  wheelOffsetY: -0.13, // центр колеса ниже центра шасси на (chassisHeight/2 + wheelRadius/2)
  /** Стартовая высота шасси над полом (центр шасси), м */
  chassisStartHeight: 0.21,

  /** Параметры ротора (вертикальный диск) */
  spinnerRadius: 0.18,
